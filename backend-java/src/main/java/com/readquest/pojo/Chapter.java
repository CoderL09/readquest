package com.readquest.pojo;

public class Chapter {
  private String id;

  public String getId() {
    return id;
  }

  public void setId(String value) {
    this.id = value;
  }

  private String bookId;

  public String getBookId() {
    return bookId;
  }

  public void setBookId(String value) {
    this.bookId = value;
  }

  private int chapterIndex;

  public int getChapterIndex() {
    return chapterIndex;
  }

  public void setChapterIndex(int value) {
    this.chapterIndex = value;
  }

  private String stageTitle;

  public String getStageTitle() {
    return stageTitle;
  }

  public void setStageTitle(String value) {
    this.stageTitle = value;
  }

  private String content;

  public String getContent() {
    return content;
  }

  public void setContent(String value) {
    this.content = value;
  }

  private String contentText;

  public String getContentText() {
    return contentText;
  }

  public void setContentText(String value) {
    this.contentText = value;
  }

  private String stageSummary;

  public String getStageSummary() {
    return stageSummary;
  }

  public void setStageSummary(String value) {
    this.stageSummary = value;
  }

  private String contentHtml;

  public String getContentHtml() {
    return contentHtml;
  }

  public void setContentHtml(String value) {
    this.contentHtml = value;
  }

  private String sourceHref;

  public String getSourceHref() {
    return sourceHref;
  }

  public void setSourceHref(String value) {
    this.sourceHref = value;
  }
}
